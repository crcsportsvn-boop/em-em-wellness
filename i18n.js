let currentLanguage = localStorage.getItem('emem_lang') || 'vi';

export function getCurrentLang() {
  return currentLanguage;
}

export function t(key) {
  const langTable = translations[currentLanguage] || translations.vi;
  return langTable[key] !== undefined ? langTable[key] : (translations.vi[key] || key);
}

export function setLanguage(lang) {
  if (lang !== 'vi' && lang !== 'en') return;
  currentLanguage = lang;
  localStorage.setItem('emem_lang', lang);
  document.documentElement.lang = lang;

  // Cập nhật thẻ Title của trang
  document.title = t('docTitle');

  // Cập nhật tất cả các phần tử có data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val !== undefined) {
      el.innerHTML = val;
    }
  });

  // Cập nhật placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key);
    if (val !== undefined) {
      el.placeholder = val;
    }
  });

  // Cập nhật title tooltip
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = t(key);
    if (val !== undefined) {
      el.title = val;
    }
  });

  // Cập nhật nhãn nút switch ngôn ngữ:
  // Nếu đang ở tiếng Việt -> hiển thị "EN"
  // Nếu đang ở tiếng Anh -> hiển thị "VIE"
  const langBtnText = document.querySelector('.lang-switch-text');
  if (langBtnText) {
    langBtnText.innerText = currentLanguage === 'vi' ? 'EN' : 'VIE';
  }

  // Cập nhật title của nút switch
  const langSwitchBtn = document.getElementById('langSwitchBtn');
  if (langSwitchBtn) {
    langSwitchBtn.title = t('langBtnTitle');
  }

  // Bắn custom event để các module khác (như app.js, date picker, anatomy viewer) cập nhật
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: currentLanguage } }));
}

export function initI18n() {
  // Gắn sự kiện click cho nút switch ngôn ngữ nổi
  const switchBtn = document.getElementById('langSwitchBtn');
  if (switchBtn) {
    switchBtn.addEventListener('click', (e) => {
      e.preventDefault();
      const nextLang = currentLanguage === 'vi' ? 'en' : 'vi';
      setLanguage(nextLang);
    });
  }

  // Khởi chạy ngôn ngữ đã lưu hoặc mặc định
  setLanguage(currentLanguage);
}
